
import streamlit as st
import pandas as pd
import joblib
import os


# --------------------------------
# 1. Page Configuration
# --------------------------------

st.set_page_config(
    page_title="Wheat Yield Prediction",
    page_icon="🌾",
    layout="wide"
)


# --------------------------------
# 2. Custom CSS
# --------------------------------

st.markdown("""
<style>

.main {
    background-color: #F7F9F7;
}

.title {
    font-size: 34px;
    font-weight: bold;
    color: #1B5E20;
}

.subtitle {
    color: #666666;
    font-size: 16px;
}

.result-box {
    background-color: #E8F5E9;
    padding: 25px;
    border-radius: 12px;
    text-align: center;
    border: 1px solid #C8E6C9;
}

.result-label {
    font-size: 18px;
    color: #2E7D32;
}

.result-value {
    font-size: 38px;
    font-weight: bold;
    color: #1B5E20;
}

</style>
""", unsafe_allow_html=True)


# --------------------------------
# 3. Load Trained Model
# --------------------------------

MODEL_PATH = "wheat_yield_model.pkl"

if os.path.exists(MODEL_PATH):

    model = joblib.load(MODEL_PATH)

else:

    st.error(
        "Model file not found! "
        "Please add wheat_yield_model.pkl "
        "to the project folder."
    )

    st.stop()


# --------------------------------
# 4. Header
# --------------------------------

st.markdown(
    '<div class="title">🌾 Wheat Yield Prediction System</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">'
    'AI-based wheat yield prediction using satellite '
    'and weather features.'
    '</div>',
    unsafe_allow_html=True
)

st.divider()


# --------------------------------
# 5. Input Section
# --------------------------------

st.subheader("📊 Enter Field Information")

st.write(
    "Enter satellite and weather information "
    "for your wheat field."
)

col1, col2 = st.columns(2)

with col1:

    st.markdown("### 🛰️ Satellite Features")

    ndvi = st.number_input(
        "NDVI",
        min_value=0.0,
        max_value=1.0,
        value=0.78,
        step=0.01
    )

    ndre = st.number_input(
        "NDRE",
        min_value=0.0,
        max_value=1.0,
        value=0.65,
        step=0.01
    )


with col2:

    st.markdown("### 🌦️ Weather Features")

    rainfall = st.number_input(
        "Seasonal Rainfall (mm)",
        min_value=0.0,
        value=300.0,
        step=1.0
    )

    temperature = st.number_input(
        "Mean Temperature (°C)",
        value=21.0,
        step=0.5
    )

    solar = st.number_input(
        "Mean Solar Radiation (MJ/m²/day)",
        min_value=0.0,
        value=18.0,
        step=0.5
    )


st.divider()


# --------------------------------
# 6. Prediction Button
# --------------------------------

if st.button(
    "🌾 Predict Wheat Yield",
    use_container_width=True,
    type="primary"
):

    # Create input DataFrame

    input_data = pd.DataFrame([{
        "NDVI": ndvi,
        "NDRE": ndre,
        "Rainfall_mm_seasonal": rainfall,
        "Mean_Temperature_C": temperature,
        "Mean_Solar_Radiation_MJ_m2_day": solar
    }])

    # Make prediction

    prediction = model.predict(input_data)[0]

    # Display result

    st.success("Prediction completed successfully!")

    st.markdown(
        f"""
        <div class="result-box">
            <div class="result-label">
                Predicted Wheat Yield
            </div>
            <div class="result-value">
                {prediction:.2f} tons/hectare
            </div>
        </div>
        """,
        unsafe_allow_html=True
    )

    # Show input summary

    st.subheader("📋 Input Data Summary")

    st.dataframe(
        input_data,
        use_container_width=True
    )

    st.info(
        "This prediction is generated by your "
        "trained Gradient Boosting model."
    )


# --------------------------------
# 7. Footer
# --------------------------------

st.divider()

st.caption(
    "Wheat Yield Prediction System | "
    "Machine Learning Project"
)
